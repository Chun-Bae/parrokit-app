/// 닉네임 규칙. 온보딩과 프로필 수정이 같은 값을 쓴다.
///
/// 전에는 프로필 수정에만 15자 제한이 있고 온보딩에는 없었다. 그래서 처음에
/// 16자가 넘는 닉네임을 만들면 나중에 프로필 수정 화면에서는 그 길이를 다시
/// 칠 수 없어 고치지도 못했다(5차).
const int nicknameMaxLength = 15;

/// 닉네임 검사 안내. 온보딩·회원가입·프로필 수정이 같은 말을 쓴다(5차 317).
///
/// 전에는 세 화면에 같은 글이 따로 적혀 있어서, 한 곳의 말을 다듬으면
/// 나머지는 예전 말로 남았다. '입력해주세요'도 앱의 다른 곳('~해 주세요')과
/// 달랐다.
const String nicknameNeededMessage = '닉네임을 적어 주세요.';
const String nicknameAvailableMessage = '쓸 수 있는 이름이에요.';
const String nicknameTakenMessage = '이미 누가 쓰고 있어요.';

/// 중복 확인을 하지 않고 저장·다음으로 가려 할 때(5차 409).
///
/// 네 화면이 세 가지 말을 쓰고 있었다. 프로필 편집은 토스트로
/// '닉네임 중복 확인을 먼저 완료해 주세요.'라 하면서, 꺼진 단추의 까닭은
/// "'중복 확인'을 먼저 눌러 주세요."라고 해 같은 화면 안에서도 달랐다.
/// 무엇을 누르면 되는지 말하는 쪽으로 맞춘다.
const String nicknameCheckNeededMessage = "'중복 확인'을 먼저 눌러 주세요.";

/// 중복 확인이 서버 쪽 사정으로 막혔을 때(5차 437).
/// 온보딩과 회원가입이 같은 말을 쓴다.
const String nicknameCheckFailedMessage = '닉네임을 확인하지 못했어요. 잠시 뒤 다시 시도해 주세요.';

/// 이름을 정하지 못했을 때. 전에는 '잘 되지 않았어요'라 무엇이 안 됐는지
/// 알 수 없었다(5차 437).
const String nicknameSaveFailedMessage = '이름을 정하지 못했어요. 다시 시도해 주세요.';
